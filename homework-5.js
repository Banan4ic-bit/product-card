/*
Задание №3
Cоздать переменную №1, которая содержит продукт и переменную №2, которая содержит его цену (на ваше усмотрение). 
Далее создаем функцию, которая принимает 1 параметр - текущий бюджет, внутри функции происходит проверка: 
если бюджет превышает цену товара - выводим лог "(ваше название товара) приобретён. Спасибо за покупку!", 
если нет - обсчитываем разницу и выводим лог "Вам не хватает X$, пополните баланс".  То-есть с помощью функции мы пытаемся приобрести товар
*/

const productName = 'Авокадо'
const productPrice = 40

function tryBuyProduct(budget) {
  if (budget >= productPrice) {
    console.log(`${productName} приобретен. Спасибо за покупку!`)
  } else {
    const scarcity = productPrice - budget 
    console.log(`Вам не хватает ${scarcity} грн, пополните баланс, нищий`)
  }
}

tryBuyProduct(4)