const LIGHT_SPEED = 299792458 

function showSpeedType(speed) {
  if (speed > LIGHT_SPEED) {
    console.log('Сверхсветовая скорость')
  } else if (speed === LIGHT_SPEED) {
    console.log('Скорость света')
  }
  else {
    console.log('Cубсветовая скорость')
  }
}

